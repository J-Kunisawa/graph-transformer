import enum


class NodeType(enum.IntEnum):
    """
    メッシュグラフ内の各格子点（ノード）の物理的・幾何学的な属性（境界条件）を定義する列挙型クラス。
    
    PyGの Data.x の特定列（node_type_index）に整数値として格納され、
    シミュレータ内でのワンホットベクトル化や、損失関数計算時のマスク処理のトリガーとして使用される。
    """
    
    # 0: 通常の領域（自由流体、あるいは連続体の中身）。物理法則に従って動的に変化するターゲット。
    NORMAL = 0
    
    # 1: 流れの中に配置された障害物（円柱など）の表面ノード。
    OBSTACLE = 1
    
    # 2: 翼型（エアフォイル）シミュレーションにおける、翼表面の幾何境界ノード。
    AIRFOIL = 2
    
    # 3: 構造解析や特定の変形制御において、強制的な変位や荷重を与える「ハンドル（把持）」ノード。
    HANDLE = 3
    
    # 4: 流体の流入境界（インフロー）。一定の流速や流量が強制的に規定される固定境界条件。
    INFLOW = 4
    
    # 5: 流体の流出境界（アウトフロー）。圧力が 0 に固定されるなど、自由流出が許容される境界。
    OUTFLOW = 5
    
    # 6: 風洞の床や天井、固定された管の壁などを表す不変の「壁面境界（ウォール）」。
    WALL_BOUNDARY = 6
    
    # 9: ワンホットベクトル（One-Hot Vector）の展開サイズ、またはモデルの埋め込み層の初期化サイズ。
    # 実際の種類数（MAX値+1）より少し大きめにマージンを持って定義されている。
    SIZE = 9


# メッシュ全体から広域的なコンテキスト（マクロな物理現象）を効率的に収集するため、
# グラフ全体に大域的アテンション（Global Attention）を張る際の基準ノードとして「壁面境界（WALL_BOUNDARY）」を指定。
GLOBAL_ATTENTION_NODE = NodeType.WALL_BOUNDARY